-- Accesso personale dalla Suite comunale (SSO Ed25519, docs/SSO.md di suite-comune).
-- Sostituisce la password unica dell'ufficio: registro attività con l'utente e token monouso.
-- Idempotente: può essere rieseguito.

-- Registro attività del modulo (chi ha fatto cosa) ----------------------------
create table if not exists mensa.registro_attivita (
  id bigint generated by default as identity primary key,
  ts timestamptz not null default now(),
  utente_id text,
  email text,
  azione text not null,
  esito text not null default 'ok',
  dettagli text not null default '{}'
);
create index if not exists registro_attivita_ts on mensa.registro_attivita (ts);

-- Token monouso della suite già usati (anti-replay) ---------------------------
create table if not exists mensa.sso_usati (
  jti text primary key,
  scade bigint not null
);

-- La password dell'ufficio non esiste più: i tentativi per IP non servono.
drop table if exists mensa.tentativi_accesso;

grant select, insert, update, delete on mensa.registro_attivita, mensa.sso_usati to mensa_app;
grant usage on all sequences in schema mensa to mensa_app;

insert into mensa.migrazioni (versione) values ('002_accesso_suite') on conflict do nothing;
